// Standalone forensic experiment against the UNMODIFIED published Apache PLC4X
// 1.0.0 packet model. The source of this experiment is Rischlab GPL-3.0-or-later.
// It never opens a socket and does not patch the published driver.
package org.rischlab.s7lab;

import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HexFormat;
import java.util.regex.Pattern;
import org.apache.plc4x.java.cotp.readwrite.COTPPacketDisconnectRequest;
import org.apache.plc4x.java.cotp.readwrite.COTPProtocolClass;
import org.apache.plc4x.java.cotp.readwrite.TPKTPacket;
import org.apache.plc4x.java.spi.buffers.api.WriteBuffer;
import org.apache.plc4x.java.spi.buffers.bytebased.WriteBufferByteBased;

public final class Plc4xDisconnectSerializerProof {
    private static final String FIXED_SOURCE_COMMIT =
        "ea229918f5d07700e04d7d69ab1645da679cb700";
    private static final int ORIGINAL_FIXED_BUFFER = 32;
    private static final int EXPECTED_TPKT_BYTES = 11;
    private static final String OBSERVED_NULL_TAIL_SHA256 =
        "c90232586b801f9558a76f2f963eccd831d9fe6775e4c8f1446b2331aa2132f2";

    private Plc4xDisconnectSerializerProof() {}

    private static String hex(byte[] b) {
        return HexFormat.of().formatHex(b);
    }

    private static String sha256(byte[] b) throws Exception {
        return hex(MessageDigest.getInstance("SHA-256").digest(b));
    }

    public static void main(String[] args) throws Exception {
        if (args.length != 0) throw new IllegalArgumentException("No network or user parameters allowed");
        final String head = System.getenv("S7_LAB_SOURCE_SHA");
        if (head == null || !Pattern.matches("[0-9a-f]{40}", head))
            throw new IllegalStateException("Requires exact current test-source SHA");

        // Use the actual 1.0.0 generated classes shipped in Maven artifacts.
        COTPPacketDisconnectRequest request = new COTPPacketDisconnectRequest(
            new ArrayList<>(), new byte[0], 0x0000, 0x0001,
            COTPProtocolClass.CLASS_0
        );
        TPKTPacket pkt = new TPKTPacket(request);
        int exactBytes = pkt.getLengthInBytes();
        if (exactBytes != EXPECTED_TPKT_BYTES)
            throw new AssertionError("Unexpected generated released packet size: " + exactBytes);

        // Original published close() uses a 32-byte backing array and writes
        // the entire resulting byte array to TCP.
        WriteBuffer oldBuffer = new WriteBufferByteBased(new byte[ORIGINAL_FIXED_BUFFER]);
        pkt.serialize(oldBuffer);
        byte[] oldWire = oldBuffer.getBytes();

        // Proposed correction: allocate only the true serialized TPKT length.
        WriteBuffer exactBuffer = new WriteBufferByteBased(new byte[exactBytes]);
        pkt.serialize(exactBuffer);
        byte[] exactWire = exactBuffer.getBytes();

        if (oldWire.length != ORIGINAL_FIXED_BUFFER || exactWire.length != exactBytes)
            throw new AssertionError("Generated byte array does not match published sizing");
        byte[] oldPrefix = Arrays.copyOfRange(oldWire, 0, exactBytes);
        byte[] unwantedTail = Arrays.copyOfRange(oldWire, exactBytes, oldWire.length);
        if (!Arrays.equals(oldPrefix, exactWire))
            throw new AssertionError("Original buffer must start with the same valid serialized TPKT");
        if (exactWire[0] != 3 || exactWire[1] != 0 ||
            ((exactWire[2] & 255) << 8 | (exactWire[3] & 255)) != exactBytes ||
            exactWire[5] != (byte) 0x80)
            throw new AssertionError("Valid original COTP Disconnect Request was not actually serialized");
        if (unwantedTail.length != 21 || !Arrays.equals(unwantedTail, new byte[21]))
            throw new AssertionError("Expected exactly the 21 zero bytes independently observed on TCP");
        if (!sha256(unwantedTail).equals(OBSERVED_NULL_TAIL_SHA256))
            throw new AssertionError("Generated 1.0.0 surplus bytes differ from actual wire fingerprint");

        System.out.println(
            "{\"schemaVersion\":1,\"sourceCommit\":\"" + head + "\""
            + ",\"publishedVersion\":\"1.0.0\""
            + ",\"releaseSourceCommit\":\"" + FIXED_SOURCE_COMMIT + "\""
            + ",\"originalBufferBytes\":" + oldWire.length
            + ",\"serializedTpktBytes\":" + exactWire.length
            + ",\"excessBytes\":" + unwantedTail.length
            + ",\"originalWireHex\":\"" + hex(oldWire) + "\""
            + ",\"exactWireHex\":\"" + hex(exactWire) + "\""
            + ",\"excessSha256\":\"" + sha256(unwantedTail) + "\""
            + ",\"exactFixPreservesTpkt\":true,\"candidateQualified\":false}"
        );
    }
}
